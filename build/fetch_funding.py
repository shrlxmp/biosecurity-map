#!/usr/bin/env python3
"""Refresh build/funding_cg.json: Coefficient Giving's biosecurity grants.

    python build/fetch_funding.py

Coefficient Giving (formerly Open Philanthropy) is the largest philanthropic
funder in biosecurity. Its site no longer has a grants index, but Trace
(https://trace.manifund.org, by Manifund) keeps a full export of the grants
database in its open repository, refreshed automatically. We read that export
and keep only grants in Coefficient Giving's own biosecurity focus areas, so
which grants count as biosecurity is the funder's call, not ours.

The output is deterministic, so a run that finds nothing new leaves the file
byte-identical and the weekly workflow commits nothing.
"""
import io
import json
import os
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "funding_cg.json")
SOURCE = ("https://raw.githubusercontent.com/manifund/trace/main/"
          "data/coefficient-grants.json")
AREAS = ["Biosecurity & Pandemic Preparedness",
         "Science Supporting Biosecurity and Pandemic Preparedness"]
MIN_GRANTS = 1000          # the full export has ~3,000; far fewer means a bad download
REQUIRED = {"id", "org", "title", "year", "amount", "areas"}


def fetch():
    request = urllib.request.Request(SOURCE, headers={
        "User-Agent": "biosecurity-map build script "
                      "(+https://github.com/shrlxmp/biosecurity-map)"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.loads(response.read().decode("utf-8"))


def validate(doc):
    """Refuse anything that isn't recognisably the full export."""
    grants = doc.get("grants") if isinstance(doc, dict) else None
    if not isinstance(grants, list) or len(grants) < MIN_GRANTS:
        raise SystemExit("refusing to use download: expected >= %d grants, got %s"
                         % (MIN_GRANTS, len(grants) if isinstance(grants, list) else "none"))
    missing = REQUIRED - set(grants[0])
    if missing:
        raise SystemExit("refusing to use download: grants missing %s"
                         % ", ".join(sorted(missing)))
    if not any(set(AREAS) & set(g.get("areas") or []) for g in grants):
        raise SystemExit("refusing to use download: no grants in the biosecurity areas")
    return grants


def main():
    print("downloading", SOURCE)
    doc = fetch()
    grants = validate(doc)
    bio = [g for g in grants if set(AREAS) & set(g.get("areas") or [])]
    bio.sort(key=lambda g: (-(g.get("date") or 0), g["id"]))
    out = {
        "_comment": "Coefficient Giving grants in its biosecurity focus areas. "
                    "Generated by build/fetch_funding.py from Trace's export; "
                    "do not edit by hand.",
        "source": SOURCE,
        "exported_at": doc.get("exported_at"),
        "areas": AREAS,
        "grants": [{"id": g["id"], "year": g["year"], "date": g.get("date"),
                    "org": (g.get("org") or "").strip(), "title": g.get("title") or "",
                    "amount": g.get("amount"),
                    "areas": [a for a in g["areas"] if a in AREAS]} for g in bio],
    }
    text = json.dumps(out, ensure_ascii=True, indent=1, sort_keys=True) + "\n"
    old = io.open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if text == old:
        print("no change: %d biosecurity grants" % len(bio))
        return
    io.open(OUT, "w", encoding="utf-8", newline="").write(text)
    total = sum(g["amount"] or 0 for g in bio)
    print("wrote %s: %d biosecurity grants, $%.1fM (of %d grants in the export)"
          % (OUT, len(bio), total / 1e6, len(grants)))


if __name__ == "__main__":
    main()
